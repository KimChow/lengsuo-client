//! 测试夹具：固定熵、固定密钥。
//!
//! ⛔ **本文件里的所有字节都是测试夹具**（合成值、非真实凭据、非真实密钥），
//! 绝不用于任何生产路径。
//!
//! 确定性来源：
//! - [`FixedEntropy`]：把固定字节序列按需切片喂给被测代码 ⇒ 输出完全确定。
//! - [`FIXED_PKCS8`]：一份**合成**的 ES256 PKCS#8 v1 DER（私钥 = 固定标量），
//!   用来产出确定性的 COSE_Key / authData / 信封向量。
//!   （`ring` 的 `SecureRandom` 是 sealed trait ⇒ 密钥生成无法注入熵，
//!   所以确定性向量走「固定私钥」这条路，而不是给密钥生成硬塞 RNG。）

#![allow(dead_code)]

use lengsuo_credential_crypto::entropy::{Entropy, EntropyError};

/// 固定熵源：按顺序吐出预置字节；用尽后返回错误（不静默重复）。
#[derive(Debug, Clone)]
pub struct FixedEntropy {
    bytes: Vec<u8>,
    pos: usize,
}

impl FixedEntropy {
    /// 从字节序列构造。
    pub fn new(bytes: &[u8]) -> Self {
        Self {
            bytes: bytes.to_vec(),
            pos: 0,
        }
    }

    /// 产出「字节 i = i mod 251」的无限序列（供需要长序列的用例）。
    pub fn repeating() -> Self {
        Self {
            bytes: (0..4096u32).map(|i| (i % 251) as u8).collect(),
            pos: 0,
        }
    }
}

impl Entropy for FixedEntropy {
    fn fill(&mut self, dest: &mut [u8]) -> Result<(), EntropyError> {
        if self.pos + dest.len() > self.bytes.len() {
            return Err(EntropyError);
        }
        dest.copy_from_slice(&self.bytes[self.pos..self.pos + dest.len()]);
        self.pos += dest.len();
        Ok(())
    }
}

