//! Python hashlib/hmac 独立执行生成，非本实现 roundtrip。
use lengsuo_wireguard::handshake::kdf3_pub;
#[test]
fn kdf3_matches_independent_python_blake2s() {
    let key = std::array::from_fn(|i| i as u8);
    let (a, b, c) = kdf3_pub(key, b"wg-kdf-audit");
    assert_eq!(
        a,
        [
            47, 146, 58, 144, 104, 103, 254, 219, 206, 200, 233, 75, 183, 66, 224, 63, 231, 131,
            247, 188, 163, 232, 160, 166, 42, 212, 190, 202, 114, 109, 39, 11
        ]
    );
    assert_eq!(
        b,
        [
            106, 151, 117, 145, 23, 41, 14, 42, 212, 179, 74, 82, 197, 241, 233, 237, 118, 4, 193,
            245, 80, 84, 159, 20, 242, 97, 171, 217, 157, 128, 0, 1
        ]
    );
    assert_eq!(
        c,
        [
            157, 254, 97, 120, 252, 52, 173, 103, 188, 174, 142, 222, 54, 228, 140, 108, 211, 198,
            32, 50, 116, 30, 255, 85, 167, 113, 79, 99, 143, 99, 143, 134
        ]
    );
}
