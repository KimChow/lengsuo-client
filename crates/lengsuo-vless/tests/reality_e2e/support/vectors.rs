//! REALITY / TLS 1.3 的**硬编码确定性向量**。
//!
//! # 来源与「非自证」原则
//!
//! 这里的期望值**不是**从本仓实现里跑出来的（那叫自证），而是取自
//! **公开标准或独立实现**：
//!
//! | 向量 | 出处 |
//! |---|---|
//! | SHA-256 / SHA-512 `"abc"` | FIPS 180-4 摘要示例 |
//! | HMAC-SHA256 / HMAC-SHA512 case 1、case 2 | RFC 4231 §4.2 / §4.3 |
//! | HKDF-SHA256 case 1 | RFC 5869 Appendix A.1 |
//! | X25519 一次迭代 / 一百万次迭代 | RFC 7748 §5.2 / §6.1 |
//! | X25519 双方公钥与共享密钥 | RFC 7748 §6.1（Alice/Bob） |
//! | Ed25519 三组公钥与签名 | RFC 8032 §7.1 TEST 1/2/3 |
//! | `Expand-Label` | RFC 8448 §3 |
//! | TLS 1.3 密钥调度各段 | RFC 8446 §7.1 的公式，独立实现复算 |
//! | REALITY `auth_key` | `HKDF-SHA256(ikm=ECDH, salt=random[:20], info="REALITY")`，独立实现复算 |
//! | 证书 REALITY 标签 | `HMAC-SHA512(auth_key, ed25519_pub)`，独立实现复算 |
//! | TLS 记录层字节 | RFC 8446 §5.2 的 `TLS_AES_128_GCM_SHA256` 构造，独立实现复算 |
//!
//! 「独立实现」指 Python 的 `cryptography`（OpenSSL 后端）与 `hashlib`/`hmac`，
//! 与本仓的纯 Rust 实现没有一行代码共享。
//!
//! **硬约束**：日志/断言消息里不得出现真实密钥。本文件的密钥全是 RFC 公开
//! 测试向量或人为假值。

