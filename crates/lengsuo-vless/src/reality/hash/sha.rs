//! REALITY 握手层所需的哈希原语**内置实现**（SHA-256 / SHA-512 / HMAC / HKDF）。
//!
//! # 为什么内置
//!
//! 参考用 Go 标准库的 `crypto/sha256`、`crypto/sha512`、`crypto/hmac` 与
//! `golang.org/x/crypto/hkdf`。本 crate 的 `[dependencies]` 里**没有**
//! `sha2` / `hmac` / `hkdf`（工作区 `Cargo.toml` 已声明这些 workspace 依赖，
//! 但要 `use` 就得改 `crates/lengsuo-vless/Cargo.toml`），而本卡的硬约束
//! 明令不得自行改 Cargo.toml。为在本卡范围内交付**可编译、可测**的实现，
//! 这里按 FIPS 180-4 / RFC 2104 / RFC 5869 逐条转写这四个原语，
//! 并用权威测试向量自证正确性（见本文件与 `auth.rs` 的测试）。
//!
//! **这是既定偏离**，已列入报告「偏离清单」：由主理人开基建卡引入
//! `sha2` + `hmac` + `hkdf` 后，本文件可整体删除、`auth.rs` 改回
//! 依赖实现（语义不变）。
//!
//! 全部为纯 Rust、无 `unsafe`、无堆分配（HKDF 输出到调用方缓冲）。

