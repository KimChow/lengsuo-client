//! 访问策略执行引擎（纯域逻辑，无 IO、无 async、无 unsafe）。
//!
//! 职责边界（唯一规格源：仓根 `POLICY-SPEC.md`）：
//! - 只维护策略数据模型（§1）、通配符 URL 模式编译与匹配（§2.5）、
//!   优先级匹配算法（§2.2–§2.4）以及操作/时间窗判定（§2.6–§2.7）。
//! - 不解析 DOM：`click_dom` 只做选择器字符串的传递与命中判定回调。
//! - 不做权威存储、不下发、不判计费与权限：策略由上层注入，本 crate 只判。
//! - 不引入 tokio/文件系统/网络；一切时间来自 `EvaluateRequest::now_ms`，可确定性复现。
//!
//! 安全底线（全部 fail-closed，AGENTS.md §3）：
//! - 没有任何策略命中、策略取不到、生效时间窗不在窗内 ⇒ 一律拒绝并在
//!   `Decision::reasons` 标明 fail-closed 原因，绝不静默放行。
//! - 模式/枚举数值在序列化层冻结，未知数值直接报错，不回退到默认变体。
//! - 规则集为空、URL 为空、选择器缺失等配置缺陷一律拒绝，不做“宽松解释”。

